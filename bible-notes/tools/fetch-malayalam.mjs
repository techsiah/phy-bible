const chapterCache = new Map();

async function getChapter(bookNum, chapter) {
  const key = `${bookNum}:${chapter}`;
  if (chapterCache.has(key)) return chapterCache.get(key);
  const url = `https://api.getbible.net/v2/mal1910/${bookNum}/${chapter}.json`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  const data = await res.json();
  chapterCache.set(key, data.verses || []);
  return data.verses || [];
}

async function main() {
  const out = [];
  for (const item of PLAN) {
    const match = item.ref.match(/^([A-Za-z]+)\s+(\d+):(.+)$/);
    if (!match) throw new Error(`Cannot parse ref: ${item.ref}`);
    const [, book, chapStr, verseRange] = match;
    const chapter = Number(chapStr);
    const refMl = `${BOOK_ML[book] || book} ${chapter}:${verseRange}`;
    const titleMl = TITLES_ML[item.day] || item.title;

    let verses;
    if (book === 'Baruch') {
      verses = BARUCH_5_ML;
    } else {
      const bookNum = BOOK_NUM[book];
      if (!bookNum) throw new Error(`Unknown book: ${book}`);
      const chapterVerses = await getChapter(bookNum, chapter);
      const byNum = new Map(chapterVerses.map((v) => [Number(v.verse), String(v.text || '').trim()]));
      verses = item.verses.map((v) => {
        const text = byNum.get(v.v);
        if (!text) throw new Error(`Missing verse ${book} ${chapter}:${v.v}`);
        return { v: v.v, t: text };
      });
    }

    out.push({
      day: item.day,
      ref: refMl,
      title: titleMl,
      verses
    });
    console.log(`Day ${item.day}: ${refMl} (${verses.length} verses)`);
  }

  const fileContent = `/* Generated by tools/fetch-malayalam.mjs — do not edit by hand.\n   Text: Malayalam Sathyavedapusthakam (1910), Public Domain.\n*/\nexport const EDITION_ML = {\n  name: 'സത്യവേദപുസ്തകം (Malayalam)',\n  short: 'MAL1910',\n  license: 'Public domain'\n};\n\nexport const PLAN_ML = ${JSON.stringify(out, null, 2)};\n`;

  await writeFile('js/plan-ml.js', fileContent, 'utf8');
  console.log('Wrote js/plan-ml.js');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
